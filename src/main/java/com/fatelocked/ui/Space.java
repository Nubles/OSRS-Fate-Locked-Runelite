package com.fatelocked.ui;

/** The spacing the sidebar is laid out on, in pixels. */
public final class Space
{
    /** Around the whole sidebar. */
    public static final int EDGE = 6;
    /** Between cards and sections. */
    public static final int GAP = 6;
    /** Inside a card. */
    public static final int PAD = 8;
    /** Between rows inside a card. */
    public static final int ROW = 4;
    /** Between an icon and its text. */
    public static final int ICON_GAP = 6;
    /** The icons beside rows and titles. */
    public static final int ICON = 16;

    private Space()
    {
    }
}
